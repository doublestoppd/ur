/*
 * standalone.js - builds the single-file distribution.
 *
 *   node build/standalone.js        (also runs automatically after a green
 *                                    `node tests/run.js`)
 *
 * Produces dist/ur-compiler.html: index.html with the stylesheet and every
 * script inlined, so the whole application ships as ONE file that can be
 * copied to a hospital workstation and double-clicked. Behavior is identical
 * to the folder distribution - same scripts, same order, still fully offline.
 *
 * index.html stays the source of truth for the script list (the unit tests
 * already parse it), so a file added there is automatically in the next
 * standalone build and a file forgotten there fails the suite.
 *
 * The build is deterministic: same inputs, same bytes. The stamp in the
 * output is a content hash, never a timestamp, so rebuilding without changes
 * never dirties the file.
 */
'use strict';

var fs = require('fs');
var path = require('path');
var crypto = require('crypto');

var ROOT = path.join(__dirname, '..');
var OUT_DIR = path.join(ROOT, 'dist');
var OUT_FILE = path.join(OUT_DIR, 'ur-compiler.html');

/*
 * Conservative minification for our own sources only: drop whole lines that
 * are comments and collapse blank runs. Nothing inside a code line is ever
 * touched (a trailing "/* flags *" + "/" stays), so it cannot corrupt strings
 * or regular expressions. The vendor bundle is already minified and is
 * inlined byte-for-byte.
 */
function stripCommentLines(source) {
  var out = [];
  var inBlock = false;
  var lines = source.split('\n');
  for (var i = 0; i < lines.length; i++) {
    var t = lines[i].trim();
    if (inBlock) {
      if (t.indexOf('*/') >= 0 && t.indexOf('*/') === t.length - 2) { inBlock = false; }
      continue;
    }
    if (t.indexOf('/*') === 0) {
      if (t.indexOf('*/') < 0) { inBlock = true; }
      continue;
    }
    if (t.indexOf('//') === 0 || t === '') { continue; }
    out.push(lines[i]);
  }
  return out.join('\n');
}

/* '</script>' inside inlined JS would end the tag early; '<\/script' is the
 * same string to the JS engine and harmless to the parser. */
function scriptSafe(js) {
  return js.replace(/<\/script/gi, '<\\/script');
}

function build() {
  var html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  var inputsHash = crypto.createHash('sha256');
  inputsHash.update(html);

  /* Inline the stylesheet. */
  var css = fs.readFileSync(path.join(ROOT, 'app.css'), 'utf8');
  inputsHash.update(css);
  html = html.replace(/<link rel="stylesheet" href="app.css">/,
    '<style>\n' + css + '\n</style>');
  if (html.indexOf('<link') >= 0) {
    throw new Error('index.html contains a <link> the standalone build does not handle.');
  }

  /* Inline every script, in the exact order index.html declares. */
  var scripts = [];
  html = html.replace(/<script src="([^"]+)"><\/script>/g, function (tag, src) {
    var js = fs.readFileSync(path.join(ROOT, src), 'utf8');
    inputsHash.update(js);
    if (src.indexOf('src/') === 0) { js = stripCommentLines(js); }
    scripts.push(src);
    return '<script>\n/* ' + src + ' */\n' + scriptSafe(js) + '\n</script>';
  });
  if (!scripts.length || html.indexOf('<script src=') >= 0) {
    throw new Error('Not every script tag was inlined.');
  }

  var stamp = '<!-- Single-file build of the CPSI UR Data Compiler. ' +
    scripts.length + ' scripts inlined; inputs sha256 ' +
    inputsHash.digest('hex').slice(0, 16) +
    '. Built by build/standalone.js - do not edit this file, edit the sources. -->\n';
  html = html.replace(/<!DOCTYPE html>\n/i, '<!DOCTYPE html>\n' + stamp);

  if (!fs.existsSync(OUT_DIR)) { fs.mkdirSync(OUT_DIR); }
  fs.writeFileSync(OUT_FILE, html);
  return { file: OUT_FILE, bytes: html.length, scripts: scripts.length };
}

module.exports = { build: build, stripCommentLines: stripCommentLines, scriptSafe: scriptSafe, OUT_FILE: OUT_FILE };

if (require.main === module) {
  var result = build();
  process.stdout.write('Built ' + path.relative(ROOT, result.file) + ' (' +
    Math.round(result.bytes / 1024) + ' KB, ' + result.scripts + ' scripts inlined)\n');
}
